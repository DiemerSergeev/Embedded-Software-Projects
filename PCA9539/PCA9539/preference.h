
#ifndef PREFERENCE_H_
#define PREFERENCE_H_

#define F_CPU 8000000UL

#include <inttypes.h>
#include <avr/io.h>
#include <avr/interrupt.h>
#include <util/delay.h>
#include <stdio.h>
#include <stdlib.h>
#include <avr/common.h>

#include "lcd0802.h"

char buffer_LCD [32];			 // для вывода на дисплей

/************************************************************************/
/* RELE                                                                 */
/************************************************************************/

#define rele_SDA_SCL_ON 	  PORTD|=0b00100000;     // переключить на формулу (PD5)
#define rele_SDA_SCL_OFF	  PORTD&=0b11011111;     // переключить на МК

#define rele_VDD_ON			  PORTD|=0b00010000;     // переключить на формулу (PD4)
#define rele_VDD_OFF          PORTD&=0b11101111;     // переключить на MK, подтяжка не запаяна

/************************************************************************/
/* ADDRESS                                                              */
/************************************************************************/

#define A0_HIGH 			  PORTA|=0b01000000;     // выставить в 1 (PA6)
#define A0_LOW				  PORTA&=0b10111111;     // выставить в 0

#define A1_HIGH 			  PORTC|=0b10000000;     // выставить в 1 (PC7)
#define A1_LOW			      PORTC&=0b01111111;     // выставить в 0

/************************************************************************/
/* RESET                                                                */
/************************************************************************/

#define RESET_HIGH 			  PORTC|=0b00000010;     // выставить VID3 в 1 (PC1)
#define RESET_LOW			  PORTC&=0b11111101;     // выставить VID3 в 0

/************************************************************************/
/* LEDS                                                                 */
/************************************************************************/

#define LED_READ_ON           PORTC|=0b00001000;     // включить светодиод READ (PC3)
#define LED_READ_OFF		  PORTC&=0b11110111;     // выключить светодиод READ

#define LED_WRITE_ON          PORTC|=0b00100000;     // включить светодиод WRITE (PC5)
#define LED_WRITE_OFF         PORTC&=0b11011111;     // выключить светодиод WRITE

/************************************************************************/
/* READY                                                                */
/************************************************************************/

#define Ready_ON			  PORTA|=0b00000001;     // пин PA0 знак готовности принимать данные от формулы (лог.1)
#define Ready_OFF		      PORTA&=0b11111110;     // пин PA0 знак загруженности принимать данные от формулы (лог.0)

#endif /* PREFERENCE_H_ */