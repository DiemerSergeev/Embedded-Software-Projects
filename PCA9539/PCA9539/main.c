	LED_WRITE_ON;                                // Включить Led2
	
	LCD_Clear();
	LCD_Setpos(0, 0);
	LCD_Str("INT PCA");
	LCD_Setpos(0, 1);
	LCD_Str("WORK");
	
	READ_ONE_BYTE(IP0);
