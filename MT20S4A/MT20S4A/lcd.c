/************************************************************************/
/* Выключение дисплея                                                   */
/************************************************************************/
void LCD_off(void)
{
	READWRITE0;
	_delay_ms(2);
	A00;
	_delay_ms(2);
	
	sendbyte(0b00000001); // clear LCD
	_delay_ms(2);
	
	sendbyte(0b00001000); // off LCD
	_delay_us(50);
}

void LCD_on(void)
{
	READWRITE0;
	_delay_ms(2);
	A00;
	_delay_ms(2);
	
	sendbyte(0b00000001); // clear LCD
	_delay_ms(2);
	
	sendbyte(0b00001100); // off LCD
	_delay_us(50);
}