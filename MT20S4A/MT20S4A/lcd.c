/************************************************************************/
/* Чистка дисплея                                                       */
/************************************************************************/
void clearlcd(void)
{
	A00;
	_delay_ms(2);
	
	READWRITE0;
	_delay_ms(2);
	
	ENABLE1;
	_delay_ms(2);
	
	sendbyte(0b00000001);
	_delay_ms(5);
	
	ENABLE0;
	_delay_ms(2);	
	
	A00;
	_delay_ms(2);
	
	READWRITE0;
	_delay_ms(2);

}
