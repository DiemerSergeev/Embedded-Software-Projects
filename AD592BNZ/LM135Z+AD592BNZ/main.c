///////////////////////////////////////////////////////////////////////////

ISR(INT0_vect)	// прерывание при приходе на PD2 лог. 1
{
	cli();
	Ready_OFF;                             // Мы не готовы принимать данные от формулы
	LED1_OFF;                              // Выключить светодиод 1

	
	if (!(PIND&0b00000100)) goto END;       // проверяем  PD2 на лог 1
	_delay_ms(8);
	if (!(PIND&0b00000100)) goto END;      // проверяем  PD2 на лог 1 через 5 мс если есть то проверяем РD3
	count=0;
	while ((PIND&0b00000100))              // сидим в цикле пока на PD2 лог. 1
	{
		if ((PIND&0b00001000))             // проверяем  PD3 на лог 1
		{
			_delay_ms(5);
			if ((PIND&0b00001000))	++count;        // проверяем  PD3 на лог 1 через 5 мс если есть то count+1 и ждём спада импульса
			while ((PIND&0b00001000)) _delay_ms(5);
		}
		
		asm("nop");
	}
	
	END:
	GIFR |= (1<<INTF0);  // сброс флага прерывания
	sei();
}

void BLINK(int n)
{
	for (int a = 0; a < n; a++)
	{
		LED1_ON;
		LED2_ON;
		_delay_ms(1000);
		LED1_OFF;
		LED2_OFF;
		_delay_ms(1000);
	}
}

/************************************************************************/
/* Описание программ                                                    */
/************************************************************************/
int main(void)
{
	Port_init();					//Инициализируем порты
	LCD_init();						//Инициализируем дисплей
	Rele_init();					//Инициализируем порты реле
	SPI_ini();                      //Инициализируем SPI
	
	Ready_OFF;                      //Мы не готовы принять данные от формулы
	LED1_ON;                       //Выключить светодиод 1
	LED2_ON;                       //Выключить светодиод 2
	_delay_ms(100);
	
	clearlcd();
	setpos(0, 0);
	str_lcd("Hello");
	setpos(0, 1);
	str_lcd("World!");
	_delay_ms(1000);
	
	LED1_OFF;                       //Выключить светодиод 1
	LED2_OFF;                       //Выключить светодиод 2
	
	clearlcd();
	setpos(0, 0);
	str_lcd("Check");
	setpos(0, 1);
	str_lcd("Sensor");
	_delay_ms(1000);
	
	count = 0;						//После включения попадаем на 0 режим
	INT_ini();						//Инициализируем прерывания
	sei();
	
	clearlcd();
	setpos(0, 0);
	str_lcd("AD592");
	setpos(0, 1);
	str_lcd("Connect");
	_delay_ms(1000);
	
/************************************************************************/
/* Поиск микросхемы AD592                                               */
/************************************************************************/
	float found_sens = 0;

	found_sens = AD592_read();
	_delay_ms(100);
	if ((found_sens<152) && (found_sens>-56.5))
	{
		clearlcd();
		setpos(0, 0);
		str_lcd("Mode 0");
		setpos(0, 1);
		str_lcd("AD Found");
		_delay_ms(1000);
	}
	else
	{
		clearlcd();
		setpos(0, 0);
		str_lcd("No sense");
		while (1)
		{
			clearlcd();
			found_sens = AD592_read();
			if ((found_sens<107) && (found_sens>-27)) break;

			setpos(0, 1);
			sprintf(buffer,"T=%.2fC", found_sens);
			str_lcd(buffer);
				
			LED1_ON;
			LED2_ON;
			_delay_ms(500);
			LED1_OFF;
			LED2_OFF;
			_delay_ms(500);
		}
			
		clearlcd();
		setpos(0, 0);
		str_lcd("Mode 0");
		setpos(0, 1);
		str_lcd("AD Found");
		_delay_ms(1000);
			
	}

/************************************************************************/
/* Режимы работы                                                        */
/************************************************************************/
	count = 0;						//После включения попадаем на 0 режим
	INT_ini();						//Инициализируем прерывания
	sei();

	while(1)
	{
		if (count == 0)
		{
			
			cli();
			clearlcd();
			setpos(0, 0);
			str_lcd("Mode: 0");
			setpos(0, 1);
			str_lcd("MK Off");
			sei();
			Ready_ON;
			LED1_ON;
			while (count==0)
			{
				asm("nop");
				asm("nop");
				if(count!=0) break;
			}
		}
		
/************************************************************************/
/* Режим 1 - Чтение температуры                                         */
/************************************************************************/
		if (count==1)
		{
			cli();
			_delay_ms(10);
			sei();
			LED1_ON;
			LED2_ON;
			
			clearlcd();
			while (count==1)
			{
				cli();
				
				found_sens = AD592_read();
										
				setpos(0, 0);
				str_lcd("Mode: 1");
										
				setpos(0, 1);
				sprintf(buffer,"T=%.2fC", found_sens);
				str_lcd(buffer);

			}
				
			sei();
			Ready_ON;
			_delay_ms(500);
			asm("nop");
		}

/************************************************************************/
/* Режим 2 - Включение реле                                             */
/************************************************************************/
		if (count==2)
		{
			cli();
			LED1_OFF;
			LED2_ON;
			clearlcd();
			setpos(0, 0);
			str_lcd("Mode: 2");
			setpos(0, 1);
			str_lcd("VOUT_F");
			rele_VOUT_F;
			_delay_ms(500);
			count=0;
			sei();
		}
		
/************************************************************************/
/* Режим 3 - Выключение реле                                            */
/************************************************************************/
		if (count==3)
		{
			cli();
			LED1_OFF;
			LED2_ON;
			clearlcd();
			setpos(0, 0);
			str_lcd("Mode: 3");
			setpos(0, 1);
			str_lcd("VOUT_ADC");
			rele_VOUT_ADC;
			_delay_ms(500);
			LED2_OFF;
			count=0;
			sei();
		}
		
/************************************************************************/
/* Обработка ошибок                                                     */
/************************************************************************/
		if (count>3)
		{
			cli();
			BLINK(3);
			clearlcd();
			setpos(0, 0);
			str_lcd("Wrong");
			setpos(0, 1);
			str_lcd("Data");
			_delay_ms(500);
			count=0;
			sei();
		}
	}
}










