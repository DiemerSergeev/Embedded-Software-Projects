#include "Preference.h"
#include "SPI.h"
static int count = 0;		 // переменная режима

//Режимы:                                          OUT1-6-DO1(PD2)                         OUT2-7-DO2(PD3)
//МК выключен:                              Удерживаем 1 пока идёт запись        (запись: 0-МК в ожидании команд (режим по умолчанию)) При включении питания читаем ID памяти
//Функциональный тест:                      Удерживаем 1 пока идёт запись        (запись: 1-Функциональный тест(Запись чтение))        В этом режиме nRST =  nWP = 2.7 В, чтение 10 блоков в цикле
//Режим токов покоя                         Удерживаем 1 пока идёт запись        (запись: 2-токи покоя)                                Ucc = 2.7 В, Fclk = 0 МГц,  nCS = nRST =  nWP = 2.7 В
//Ток потребления 20 МГц                    Удерживаем 1 пока идёт запись        (запись: 3-чтение на 20 МГц)                          Режим цикличного чтения (Ucc = 3.6 В)
//Токи утечки (CS,SCK,MI)                   Удерживаем 1 пока идёт запись        (запись: 4-реле 1,2 вкл. (CS,SCK,MI))                 Токи утечки (Ucc = 2.7 В) (Вкл реле 1,2; nWP = nRST = 2.7 В)
//Откл. все реле (1,2,3)                    Удерживаем 1 пока идёт запись        (запись: 5-реле 1,2,3 выкл. (CS,SCK,MI,MO))           Выкл реле 1,2,3; nWP = nRST = 2.7 В
//Низкий уровень 0x00 (MO)                  Удерживаем 1 пока идёт запись        (запись: 6-низкий уровень 0x00)                       Выходные уровни на MO (нужно стереть блок с адреса 0x00, записать туда 0x00, начать чтение и стопнуть,переключить 3 реле и IN-OUT1-23-DI1(PA6) удерживать 3 секунды, после чего отключить 3 реле и IN-OUT1-23-DI1(PA6), стереть блок с адреса 0x00) (Ucc = 2.7 В)
//Высокий уровень 0xFF (MO)                 Удерживаем 1 пока идёт запись        (запись: 7-высокий уровень запись 0xFF)               Выходные уровни на MO (нужно стереть блок с адреса 0x00, начать чтение и стопнуть,переключить 3 реле и IN-OUT1-23-DI1(PA6) удерживать 3 секунды, после чего отключить 3 реле и IN-OUT1-23-DI1(PA6))

//Реле 1 - PA3(Управляет CS и SCK) по умолчанию на линии контроллера
//Реле 2 - PA4(Управляет MI) по умолчанию на линии контроллера
//Реле 3 - PA5(Управляет MO) по умолчанию на линии контроллера
//Реле 4 - PA2(управляет nHOLD и nWP) по умолчанию на линии контроллера

//Ready - PA6 (Сигнал готовности МК)

//nHOLD - PB2
//nWP - PB3
//nCS - PB4
//MO - PB5 (выход МК)
//MI - PB6 (вход МК)
//SCK - PB7

//LED 1 - PB0 (WRITE)
//LED 2 - PB1 (READ)

/*-----------------------Подпрограммы--------------------------------*/
void Port_init(void)
{
	PORTA = 0x00;
	DDRA = (0<<7)|(1<<6)|(1<<5)|(1<<4)|(1<<3)|(0<<2)|(0<<1)|(0<<0);  //DDRA
	
	PORTB = 0x10; //CS в HIGH PORT 4
	DDRB = (1<<7)|(0<<6)|(1<<5)|(1<<4)|(0<<3)|(0<<2)|(1<<1)|(1<<0);  //DDRB
	
	PORTC = 0x00;
	DDRC = (0<<7)|(0<<6)|(0<<5)|(0<<4)|(0<<3)|(0<<2)|(0<<1)|(0<<0);  //DDRC
	
	PORTD = 0x00;
	DDRD = (0<<7)|(0<<6)|(0<<5)|(0<<4)|(0<<3)|(0<<2)|(0<<1)|(0<<0);  //DDRD
	
	LED1_ON;
	LED2_ON;
}

void INT_ini(void)
{
	DDRD  &= 0b11110011;			   // PD2, PD3 на вход
	PORTD &= 0b11110011;			   // PD2, PD3 на вход
	
	MCUCR |= (1<<ISC01) | (1<<ISC00);  // прерывание по фронту
	GICR  |= (1<<INT0);				   // PD2- INT0
	GIFR  |= (1<<INTF0);			   // сброс флага прерывания
}

void Rele_init(void)
{
	DDRA  |= 0b00111100;	  // реле
	PORTA &= 0b11000011;      // все реле выключены
}

ISR(INT0_vect)	                            // прерывание при приходе на PD2 лог. 1
{
	cli();
	Ready_OFF;                              // Мы не готовы принимать данные от формулы
	LED1_OFF;                               // Выключить светодиод LED1
	LED2_ON;                                // Включить Led2

	if (!(PIND&0b00000100)) goto END;       // проверяем  PD2 на лог 1
	_delay_ms(8);
	if (!(PIND&0b00000100)) goto END;       // проверяем  PD2 на лог 1 через 5 мс если есть то проверяем РD3
	count=0;
	
	while ((PIND&0b00000100))               // сидим в цикле пока на PD2 лог. 1
	{
		if ((PIND&0b00001000))              // проверяем  PD3 на лог 1
		{
			_delay_ms(5);
			if ((PIND&0b00001000)) ++count;                    // проверяем  PD3 на лог 1 через 5 мс если есть то count+1 и ждём спада импульса
			while ((PIND&0b00001000)) _delay_ms(5);
		}
		asm("nop");
	}
	
	END:
	GIFR |= (1<<INTF0);                    //Cброс флага прерывания
	sei();
}

void Problem()
{
	LED2_OFF;                              //Выключить светодиод LED2
	Ready_OFF;                             //Мы не готовы принять данные от формулы
	while(1)
	{
		LED1_ON;                          // Включить светодиод LED1
		_delay_ms(300);
		LED1_OFF;                         // Выключить светодиод LED1
		_delay_ms(300);
	}
}

void BLINK(uint8_t count)                 // Просто мигание показывающее выбранный режим
{
	for (uint8_t i=0;i<count;i++)
	{
		LED2_ON;
		_delay_ms(200);
		LED2_OFF;
		_delay_ms(200);
	}
}

int main(void)
{
/************************************************************************/
/* Инициализация и настройки переферии                                  */
/************************************************************************/
	Port_init();      // Инициализация портов
	_delay_ms(100);
	
	Rele_init();      // Инициализация портов реле
	_delay_ms(100);
	
	SPI_INI();        // Инициализация SPI
	_delay_ms(100);
	
	INT_ini();
	_delay_ms(100);
		
	MemBuf_WRITE();
	_delay_ms(100);
	
/************************************************************************/
/* ПРОВЕРКА СТАТУСА РАБОТЫ МИКРОСХЕМЫ                                   */
/************************************************************************/
	Ready_OFF;
	LED2_ON;
	LED1_ON;
	uint16_t address = 0x0000;
/************************************************************************/
/* WRITE ENABLE CHECK                                                   */
/************************************************************************/
	nCS_ON;
	
	SPDR = WREN;
	while(!(SPSR & (1<<SPIF)));
	
	nCS_OFF;
/************************************************************************/
/* ФУНКЦИОНАЛЬНЫЙ КОНТРОЛЬ РАБОТЫ ПАМЯТИ                                */
/************************************************************************/		
	if (CHECK_PAGE(address)!=1) // Проверка наличия микросхемы памяти
	{
		Ready_OFF;             // Память не обнаружена выставляем DI1(PA6) в лог. 1
		LED1_OFF;              // Выключили светодиод WRITE
		LED2_OFF;
		while(1)               // Мигаем зелёным светодиодом PWR, означает что память не обнаружена
		{
			BLINK(3);
			_delay_ms(1000);
		}
	}
	address = 0x0000;
	MemBuf_WRITE1();
	WRITE_PAGE(address);
	_delay_ms(100);

	LED1_ON;
	LED2_ON;
	Ready_ON;
	count = 0;
	sei();	

    while (1) 
    {
/************************************************************************/
/* Режим 0  - Режим МК не работает                                      */
/************************************************************************/
		if (count == 0)
		{
			Ready_ON
			LED1_ON;
			LED2_ON;

			sei();
			while (count == 0)
			{
				asm("nop");
				asm("nop");
				BLINK(1);
				_delay_ms(100);
			}
		}
/************************************************************************/
/* Режим 1 - Режим Функциональный тест чтения и записи всех страниц     */
/************************************************************************/
		if (count == 1)
		{
			Ready_OFF;
			cli();
			BLINK(1);

			MemBuf_WRITE();
			address = 0x0000;
			_delay_ms(100);
			for (int i=0; i<512; i++)
			{
				if(CHECK_PAGE(address)!=1) Problem();
				address+=128;
				_delay_ms(1);
			}
			address = 0x0000;
			_delay_ms(100);
			sei();
			Ready_ON;
			count = 0;
		}
/************************************************************************/
/* Режим 2 - Режим токов потребления CS=HIGH                            */
/************************************************************************/
		if (count == 2)
		{
			Ready_OFF;
			cli();
			BLINK(2);
						
			nCS_OFF;
			sei();
			while (count==2)
			{
				_delay_ms(100);	
			}
			Ready_ON;
		}
/************************************************************************/
/* Режим 3 - Режим ток потребления в режиме чтения                      */
/************************************************************************/
		if (count == 3)
		{
			Ready_OFF; 
			cli();
			BLINK(3);
			
			address = 0x0000;
			MemBuf_WRITE();
			for (int i=0; i<512; i++)
			{
				_delay_us(5);
				WRITE_PAGE(address);
				address+=128;
			}
			address = 0x0000;

			rele_MI_ON;
			nCS_ON;
			
			while(count==3)
			{
				_delay_us(5);
				SPDR = READ_CMD;                           // Read Sequence READ Opcode 03h
				while(!(SPSR & (1<<SPIF)));

				SPDR = (uint8_t)address&0xFF00;                 // Address first byte
				while(!(SPSR & (1<<SPIF)));
				
				SPDR = (uint8_t)(address&0x00FF)>>8;            // Address second byte
				while(!(SPSR & (1<<SPIF)));
				
				for(int i = 0; i<128; i++)           // ЗАПИСЫВАЕМ В СВОЙ БУФФФЕР ДАННЫЕ С МК
				{
					SPDR = 0x00;
					while(!(SPSR & (1<<SPIF)));
					mem_buff2[i] = SPDR;
				}
				address += 128;
			}
			address = 0x0000;
			sei();
			_delay_ms(100);
			Ready_ON;
		}
/************************************************************************/
/* Режим 4 - Режим токи утечки ВКЛЮЧЕНИЕ РЕЛЕ CS/SCK/MOSI               */
/************************************************************************/
		if (count == 4)
		{
			Ready_OFF;
			cli();   
			BLINK(4);
				
			rele_CSSCK_ON;
			rele_MI_ON;
			rele_nWPnHOLD_ON;
			_delay_ms(100);
			
			sei();
			Ready_ON;
			count = 0;
		}
/************************************************************************/
/* Режим 5 - Режим отключены все реле (1, 2, 3, 4)                      */
/************************************************************************/
		if (count == 5)
		{
			Ready_OFF;
			cli();
			BLINK(5);

			rele_CSSCK_OFF;      // переключить CS,SCK на МК (PA3)
			rele_MI_OFF;         // переключить MI на МК (PA4)
			rele_MO_OFF;         // переключить MO на МК (PA5)
			rele_nWPnHOLD_OFF;   // переключить nWP,nHOLD на МК
			_delay_ms(100);
			
			Ready_ON;
			sei();
			Ready_ON;
			count = 0;
		}
/************************************************************************/
/* Режим 6 - Режим низкий уровень 0х00 (MO)                             */
/************************************************************************/
		if (count == 6)
		{
			Ready_OFF;
			cli();
			
			LED1_OFF;
			LED2_OFF;

			address = 0x0000;
			MemBuf_WRITE0();
			WRITE_PAGE(address);
			_delay_ms(100);
			
			SPI_Off();
			
/************************************************************************/
/* Ручной режим чтения                                                  */
/************************************************************************/			
			nCS_ON;
			for (int i=0; i<6; i++)
			{
				MO_0;
				SCK_1;
				_delay_us(5);
				SCK_0;
				_delay_us(5);
			}
			for (int i=6; i<8; i++)
			{
				MO_1;
				SCK_1;
				_delay_us(5);
				SCK_0;
				_delay_us(5);
			}
			for (int i=0; i<16; i++)
			{
				MO_0;
				SCK_1;
				_delay_us(5);
				SCK_0;
				_delay_us(5);
			}
			for (int i=0; i<5; i++)
			{
				MO_0;
				SCK_1;
				_delay_us(5);
				SCK_0;
				_delay_us(5);
			}
			SCK_1;
/////////////////////////////////////////////////
			rele_MO_ON;
			LED1_ON;
			LED2_ON;
			_delay_ms(5000);
			LED1_OFF;
			LED2_OFF;
			rele_MO_OFF;
////////////////////////////////////////////////
			for (int i=5; i<8; i++)
			{
				MO_0;
				SCK_1;
				_delay_us(5);
				SCK_0;
				_delay_us(5);
			}
			nCS_OFF;
			_delay_ms(100);
			SPI_INI();

			Ready_ON;
			sei();
			Ready_ON;
			count = 0;
		}
/************************************************************************/
/* Режим 7 - Режим высокий уровень 0xFF (MO)                            */
/************************************************************************/
		if (count == 7)
		{
			Ready_OFF; 
			cli();
			LED1_OFF;
			LED2_OFF;
			
			address = 0x0000;
			MemBuf_WRITE1();
			WRITE_PAGE(address);      // Пишем в память буфер

			SPI_Off();
			_delay_ms(100);
/************************************************************************/
/* Ручной режим чтения                                                  */
/************************************************************************/
			nCS_ON;
			for (int i=0; i<6; i++)
			{
				MO_0;
				SCK_1;
				_delay_us(5);
				SCK_0;
				_delay_us(5);
			}
			for (int i=6; i<8; i++)
			{
				MO_1;
				SCK_1;
				_delay_us(5);
				SCK_0;
				_delay_us(5);
			}
			for (int i=0; i<16; i++)
			{
				MO_0;
				SCK_1;
				_delay_us(5);
				SCK_0;
				_delay_us(5);
			}
			for (int i=0; i<5; i++)
			{
				MO_0;
				SCK_1;
				_delay_us(5);
				SCK_0;
				_delay_us(5);
			}
			SCK_1;
/////////////////////////////////////////////////
			rele_MO_ON;
			LED1_ON;
			LED2_ON;
			_delay_ms(5000);
			LED1_OFF;
			LED2_OFF;
			rele_MO_OFF;
////////////////////////////////////////////////
			for (int i=5; i<8; i++)
			{
				MO_0;
				SCK_1;
				_delay_us(5);
				SCK_0;
				_delay_us(5);
			}
			nCS_OFF;
			_delay_ms(100);
			
			SPI_INI();
			sei();
			Ready_ON;
			count = 0;
		}	
/************************************************************************/
/* Режим 8 - Сброс памяти в 0xFF                                        */
/************************************************************************/
		if (count==8)
		{
			Ready_OFF;
			cli();
			BLINK(8);
			
			address = 0x0000;
			MemBuf_WRITE1();
			for (int i=0; i<512; i++)
			{
				WRITE_PAGE(address);      // Пишем в память буфер
				_delay_us(5);
				address += 128;
			}
			address = 0x0000;
			sei();
			Ready_ON;
			count = 0;
		}

/************************************************************************/
/* Ошибки                                                               */
/************************************************************************/
		if (count > 9)
		{
			Ready_OFF;
			cli();
			_delay_ms(100);
			sei();
			
			BLINK(9);
			_delay_ms(100);
			Ready_ON;
			count = 0;
		}
	}
}

